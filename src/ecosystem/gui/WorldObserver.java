package ecosystem.gui;

/**
 * ממשק המאזין המשמש כחלק מתבנית העיצוב אובזרבר בעולם שלנו
 * כל מחלקה שרוצה לקבל עדכון אוטומטי בכל פעם שמשהו משתנה בסביבה האקולוגית חייבת לממש את הממשק הזה
 */
public interface WorldObserver {

    /**
     * מתודת עדכון שמערכת הליבה מפעילה באופן אוטומטי ברגע שחל שינוי בעולם
     * מתודה זו גורמת לרכיבים המממשים אותה כמו המפה או פאנל הסטטיסטיקה לרענן את התצוגה שלהם ולהציג את הנתונים החדשים
     */
    void onWorldChanged();
}